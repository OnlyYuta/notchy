import Foundation
import AppKit
import SwiftUI
import Combine

public final class ClipboardService: ObservableObject {
    public static let shared = ClipboardService()
    
    @Published public private(set) var items: [ClipboardItem] = []
    @Published public var justPastedId: UUID? = nil
    @Published public var searchText: String = ""
    
    private var lastChangeCount: Int = -1
    private var pollTimer: Timer?
    private let maxItems: Int = 50
    
    private var storageURL: URL {
        let fileManager = FileManager.default
        let appSupport = fileManager.urls(for: .applicationSupportDirectory, in: .userDomainMask).first!
        let dir = appSupport.appendingPathComponent("Notchy", isDirectory: true)
        if !fileManager.fileExists(atPath: dir.path) {
            try? fileManager.createDirectory(at: dir, withIntermediateDirectories: true, attributes: nil)
        }
        return dir.appendingPathComponent("clipboard_history.json")
    }
    
    public var filteredItems: [ClipboardItem] {
        let query = searchText.trimmingCharacters(in: .whitespacesAndNewlines)
        if query.isEmpty {
            return items
        }
        return items.filter { $0.text.localizedCaseInsensitiveContains(query) }
    }
    
    public init() {
        loadHistory()
        // Register initial pasteboard content if any
        checkPasteboard()
        if SettingsService.shared.isTabVisible(.clipboard) { startPolling() }
    }
    
    /// The Clipboard tab switched off in settings: no pasteboard polling at all
    public func setEnabled(_ on: Bool) {
        pollTimer?.invalidate()
        pollTimer = nil
        if on { checkPasteboard(); startPolling() }
    }
    
    deinit {
        pollTimer?.invalidate()
    }
    
    private func startPolling() {
        pollTimer = Timer.scheduledTimer(withTimeInterval: 1.5, repeats: true) { [weak self] _ in
            self?.checkPasteboard()
        }
    }
    
    public func checkPasteboard() {
        let pb = NSPasteboard.general
        let currentChangeCount = pb.changeCount
        guard currentChangeCount != lastChangeCount else { return }
        lastChangeCount = currentChangeCount
        
        // Filter out concealed types from password managers (1Password, Bitwarden, Keychain)
        let concealedTypes: [NSPasteboard.PasteboardType] = [
            NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
            NSPasteboard.PasteboardType("com.agilebits.onepassword"),
            NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
            NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType")
        ]
        for t in concealedTypes {
            if pb.data(forType: t) != nil { return }
        }
        
        guard let string = pb.string(forType: .string), string.count <= 100_000 else { return }
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return }
        
        // Avoid adding duplicate if it is already the top item
        if let first = items.first, first.kind == .text, first.text == string {
            return
        }
        
        DispatchQueue.main.async { self.insert(ClipboardItem(text: string, timestamp: Date())) }
    }
    
    /// Puts an item on top of the history, replacing an identical one, and trims to `maxItems`.
    private func insert(_ item: ClipboardItem) {
        withAnimation(.spring(response: 0.35, dampingFraction: 0.8)) {
            let duplicates = items.filter { $0.kind == item.kind && $0.text == item.text && $0.paths == item.paths }
            duplicates.forEach { removeStoredImage(of: $0, unlessSameAs: item) }
            items.removeAll { dup in duplicates.contains { $0.id == dup.id } }
            items.insert(item, at: 0)
            if items.count > maxItems {
                items.suffix(from: maxItems).forEach { removeStoredImage(of: $0) }
                items = Array(items.prefix(maxItems))
            }
        }
        saveHistory()
    }
    
    // MARK: - Dropped files, folders, images
    
    /// Called when something is dropped on the notch. Files and folders are kept by reference (nothing is copied).
    public func add(files urls: [URL]) {
        let urls = urls.filter { $0.isFileURL }
        guard !urls.isEmpty else { return }
        let names = urls.map { $0.lastPathComponent }.joined(separator: ", ")
        insert(ClipboardItem(text: names, kind: .file, paths: urls.map { $0.path }))
    }
    
    /// Image without a file behind it (for example dragged out of a web page): saved as PNG so it survives.
    public func add(imageData: Data) {
        guard let rep = NSBitmapImageRep(data: imageData), let png = rep.representation(using: .png, properties: [:]) else { return }
        let dir = storedFilesDirectory
        let url = dir.appendingPathComponent("\(UUID().uuidString).png")
        guard (try? png.write(to: url, options: .atomic)) != nil else { return }
        insert(ClipboardItem(text: tr("Изображение", "Image"), kind: .image, paths: [url.path]))
    }
    
    public func add(text: String) {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return }
        insert(ClipboardItem(text: text))
    }
    
    private var storedFilesDirectory: URL {
        let dir = storageURL.deletingLastPathComponent().appendingPathComponent("ClipboardFiles", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir
    }
    
    private func removeStoredImage(of item: ClipboardItem, unlessSameAs other: ClipboardItem? = nil) {
        guard item.kind == .image else { return }
        for path in item.paths where path.hasPrefix(storedFilesDirectory.path) && !(other?.paths.contains(path) ?? false) {
            try? FileManager.default.removeItem(atPath: path)
        }
    }
    
    // MARK: - Actions
    
    /// Copies item text to pasteboard, shows visual feedback, and synthesizes Cmd+V to paste into active input
    public func paste(item: ClipboardItem) {
        let pb = NSPasteboard.general
        write(item, to: pb)
        self.lastChangeCount = pb.changeCount
        
        // Visual feedback
        withAnimation(.spring(response: 0.25, dampingFraction: 0.75)) {
            self.justPastedId = item.id
        }
        
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.4) { [weak self] in
            if self?.justPastedId == item.id {
                withAnimation(.easeOut(duration: 0.25)) {
                    self?.justPastedId = nil
                }
            }
        }
        
        // Synthesize Cmd+V to paste into active text cursor
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.06) {
            self.synthesizePasteCommand()
        }
    }
    
    /// Copies item text to pasteboard without synthesizing Cmd+V
    public func copyOnly(item: ClipboardItem) {
        let pb = NSPasteboard.general
        write(item, to: pb)
        self.lastChangeCount = pb.changeCount
        
        withAnimation(.spring(response: 0.25, dampingFraction: 0.75)) {
            self.justPastedId = item.id
        }
        
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            if self?.justPastedId == item.id {
                withAnimation(.easeOut(duration: 0.2)) {
                    self?.justPastedId = nil
                }
            }
        }
    }
    
    /// Text goes as a string; files, folders and images go as file URLs (plus image data), so Finder, chats and editors accept them.
    private func write(_ item: ClipboardItem, to pb: NSPasteboard) {
        pb.clearContents()
        switch item.kind {
        case .text:
            pb.setString(item.text, forType: .string)
        case .file:
            pb.writeObjects(item.urls.map { $0 as NSURL })
        case .image:
            if let url = item.urls.first, let image = NSImage(contentsOf: url) {
                pb.writeObjects([url as NSURL, image])
            }
        }
    }
    
    public func delete(item: ClipboardItem) {
        removeStoredImage(of: item)
        withAnimation(.spring(response: 0.3, dampingFraction: 0.8)) {
            self.items.removeAll(where: { $0.id == item.id })
        }
        saveHistory()
    }
    
    public func clearAll() {
        items.forEach { removeStoredImage(of: $0) }
        withAnimation(.spring(response: 0.3, dampingFraction: 0.8)) {
            self.items.removeAll()
        }
        saveHistory()
    }
    
    // MARK: - Key Event Synthesis
    
    private func synthesizePasteCommand() {
        let src = CGEventSource(stateID: .combinedSessionState)
        let vKeyCode: CGKeyCode = 0x09 // Virtual key code for 'V'
        
        guard let keyDown = CGEvent(keyboardEventSource: src, virtualKey: vKeyCode, keyDown: true),
              let keyUp = CGEvent(keyboardEventSource: src, virtualKey: vKeyCode, keyDown: false) else {
            return
        }
        
        keyDown.flags = .maskCommand
        keyUp.flags = .maskCommand
        
        keyDown.post(tap: .cghidEventTap)
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.015) {
            keyUp.post(tap: .cghidEventTap)
        }
    }
    
    // MARK: - Persistence
    
    private func saveHistory() {
        let url = storageURL
        let itemsSnapshot = self.items
        DispatchQueue.global(qos: .utility).async {
            do {
                let data = try JSONEncoder().encode(itemsSnapshot)
                try data.write(to: url, options: .atomic)
            } catch {
                // Ignore error if disk write fails
            }
        }
    }
    
    private func loadHistory() {
        let url = storageURL
        if let data = try? Data(contentsOf: url),
           let loaded = try? JSONDecoder().decode([ClipboardItem].self, from: data) {
            self.items = loaded
        }
    }
}
